#!/usr/bin/env python3
"""Generate deterministic C assets for the shared MFCC frontend."""

import argparse
from pathlib import Path

import numpy as np

try:
    from .acoustic_frontend import (
        CONFIG_PATH,
        config_sha256,
        load_config,
        load_config_data,
        make_dct_matrix,
        make_mel_filterbank,
        make_periodic_hann,
    )
except ImportError:
    from acoustic_frontend import (
        CONFIG_PATH,
        config_sha256,
        load_config,
        load_config_data,
        make_dct_matrix,
        make_mel_filterbank,
        make_periodic_hann,
    )


SCRIPT_DIRECTORY = Path(__file__).resolve().parent
DEFAULT_OUTPUT_DIRECTORY = SCRIPT_DIRECTORY / "stm32_frontend"
DEFAULT_LEGACY_HEADER = SCRIPT_DIRECTORY / "mel_filterbank.h"


def format_float(value):
    value = np.float32(value)
    if value == 0:
        value = np.float32(0)
    return f"{value:.9e}f"


def format_flat_array(values, values_per_line=6, indent="    "):
    flattened = np.asarray(values).reshape(-1)
    lines = []
    for start in range(0, len(flattened), values_per_line):
        chunk = flattened[start:start + values_per_line]
        suffix = "," if start + values_per_line < len(flattened) else ""
        lines.append(
            indent + ", ".join(format_float(value) for value in chunk) + suffix
        )
    return "\n".join(lines)


def render_config_header(config, config_hash):
    return f"""/* Generated by generate_frontend_assets.py. Do not edit. */
#ifndef MFCC_FRONTEND_CONFIG_H
#define MFCC_FRONTEND_CONFIG_H

#define MFCC_FRONTEND_CONFIG_SHA256 \"{config_hash}\"
#define MFCC_FRONTEND_SAMPLE_RATE {config.sample_rate}U
#define MFCC_FRONTEND_CLIP_SAMPLES {config.clip_sample_count}U
#define MFCC_FRONTEND_FFT_SIZE {config.n_fft}U
#define MFCC_FRONTEND_FFT_BINS {config.n_fft_bins}U
#define MFCC_FRONTEND_HOP_LENGTH {config.hop_length}U
#define MFCC_FRONTEND_FRAME_COUNT {config.number_of_frames}U
#define MFCC_FRONTEND_MEL_COUNT {config.n_mels}U
#define MFCC_FRONTEND_MFCC_COUNT {config.n_mfcc}U
#define MFCC_FRONTEND_MODEL_CHANNELS {config.model_input_shape[2]}U
#define MFCC_FRONTEND_PCM_INT16_SCALE ({format_float(config.pcm_int16_scale)})
#define MFCC_FRONTEND_DB_AMIN ({format_float(config.power_to_db_amin)})
#define MFCC_FRONTEND_DB_REFERENCE ({format_float(config.power_to_db_reference)})
#define MFCC_FRONTEND_TOP_DB ({format_float(config.power_to_db_top_db)})

#endif
"""


def render_data_header():
    return """/* Generated by generate_frontend_assets.py. Do not edit. */
#ifndef MFCC_FRONTEND_DATA_H
#define MFCC_FRONTEND_DATA_H

#include "mfcc_frontend_config.h"

extern const float g_mfcc_frontend_window[MFCC_FRONTEND_FFT_SIZE];
extern const float g_mfcc_frontend_mel_filterbank[
    MFCC_FRONTEND_MEL_COUNT * MFCC_FRONTEND_FFT_BINS
];
extern const float g_mfcc_frontend_dct_matrix[
    MFCC_FRONTEND_MFCC_COUNT * MFCC_FRONTEND_MEL_COUNT
];

#endif
"""


def render_data_source(window, mel_filterbank, dct_matrix):
    return f"""/* Generated by generate_frontend_assets.py. Do not edit. */
#include "mfcc_frontend_data.h"

const float g_mfcc_frontend_window[MFCC_FRONTEND_FFT_SIZE] = {{
{format_flat_array(window)}
}};

const float g_mfcc_frontend_mel_filterbank[
    MFCC_FRONTEND_MEL_COUNT * MFCC_FRONTEND_FFT_BINS
] = {{
{format_flat_array(mel_filterbank)}
}};

const float g_mfcc_frontend_dct_matrix[
    MFCC_FRONTEND_MFCC_COUNT * MFCC_FRONTEND_MEL_COUNT
] = {{
{format_flat_array(dct_matrix)}
}};
"""


def render_legacy_mel_header(config, mel_filterbank, config_hash):
    rows = []
    for row_index, row in enumerate(mel_filterbank):
        suffix = "," if row_index + 1 < len(mel_filterbank) else ""
        rows.append("    {\n" + format_flat_array(row, indent="        ") + "\n    }" + suffix)

    return f"""/* Generated by generate_frontend_assets.py. Do not edit. */
#ifndef MEL_FILTERBANK_H
#define MEL_FILTERBANK_H

#define MEL_FILTERBANK_CONFIG_SHA256 \"{config_hash}\"
#define NUM_MEL_FILTERS {config.n_mels}
#define NUM_FFT_BINS {config.n_fft_bins}

static const float mel_filterbank[NUM_MEL_FILTERS][NUM_FFT_BINS] = {{
{chr(10).join(rows)}
}};

#endif
"""


def generated_files(config_path, output_directory, legacy_header):
    config_data = load_config_data(config_path)
    config = load_config(config_path)
    config_hash = config_sha256(config_data)
    window = make_periodic_hann(config)
    mel_filterbank = make_mel_filterbank(config)
    dct_matrix = make_dct_matrix(config)

    files = {
        output_directory / "mfcc_frontend_config.h": render_config_header(
            config,
            config_hash,
        ),
        output_directory / "mfcc_frontend_data.h": render_data_header(),
        output_directory / "mfcc_frontend_data.c": render_data_source(
            window,
            mel_filterbank,
            dct_matrix,
        ),
    }
    if legacy_header is not None:
        files[legacy_header] = render_legacy_mel_header(
            config,
            mel_filterbank,
            config_hash,
        )
    return config_hash, files


def write_or_check(files, check):
    stale = []
    for path, content in files.items():
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(path)
            continue

        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"generated: {path}")

    if stale:
        stale_text = "\n".join(f"  - {path}" for path in stale)
        raise SystemExit(
            "Generated frontend assets are missing or stale:\n"
            f"{stale_text}\n"
            "Run: python dataset_processing/generate_frontend_assets.py"
        )


def parse_arguments():
    parser = argparse.ArgumentParser(
        description="Generate CMSIS-DSP MFCC constants from the JSON config."
    )
    parser.add_argument("--config", type=Path, default=CONFIG_PATH)
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIRECTORY,
    )
    parser.add_argument(
        "--legacy-mel-header",
        type=Path,
        default=DEFAULT_LEGACY_HEADER,
        help="Also update the existing standalone Mel header.",
    )
    parser.add_argument(
        "--no-legacy-mel-header",
        action="store_true",
        help="Do not generate dataset_processing/mel_filterbank.h.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if generated files differ instead of writing them.",
    )
    return parser.parse_args()


def main():
    args = parse_arguments()
    legacy_header = None if args.no_legacy_mel_header else args.legacy_mel_header
    config_hash, files = generated_files(
        args.config.resolve(),
        args.output_dir.resolve(),
        legacy_header.resolve() if legacy_header is not None else None,
    )
    write_or_check(files, args.check)
    print(f"frontend config sha256: {config_hash}")


if __name__ == "__main__":
    main()
